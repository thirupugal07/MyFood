/** Build a menu array from compact tuples: [name, price, description, section, flags] */
const buildMenu = (rows, images) =>
  rows.map((row, index) => {
    const [name, price, description, section, flags = ''] = row;
    return {
      id: slugify(name),
      name,
      price,
      description,
      section,
      image: images[index % images.length],
      isVeg: flags.includes('v'),
      isBestseller: flags.includes('b'),
      isSpicy: flags.includes('s'),
      isAvailable: !flags.includes('x'),
    };
  });

